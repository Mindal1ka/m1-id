def demo_payload(section: str) -> dict | None:
    """Сирий формат mapi (schedule/get-month?type=week) для демо-тижня
    або None, якщо секція не про нього."""
    # дашборд використовує секцію БЕЗ дати («schedule_week»), вкладка
    # розкладу — «schedule_week@<понеділок>»: обслуговуємо обидві
    if section != "schedule_week" and not section.startswith("schedule_week@"):
        return None
    if "@" in section:
        arg = section.split("@", 1)[1]
        try:
            d = date.fromisoformat(arg)
        except ValueError:
            return None
        # будь-яка дата → її понеділок (як робить роутер)
        d = d - timedelta(days=d.weekday())
        if d.isoformat() != DEMO_MONDAY:
            return None

    data: list[dict] = []
    for day_i in range(6):  # Пн–Сб (субота — демо «7 уроків сьогодні»)
        day = date(DEMO_START.year, DEMO_START.month,
                   DEMO_START.day + day_i)
        subjects = _DAYS[day_i]
        for n, subj in enumerate(subjects):
            st, fin = _PERIODS[n]
            has_mark = day_i < 4 and n in (0, 2, 3)
            row = {
                "date": day.isoformat(),
                "week_day": str(day.isoweekday()),
                "lesson": n + 1,
                "started_at": f"{st}:00",
                "finished_at": f"{fin}:00",
                "subject_name": subj,
                "lesson_theme": _THEMES.get(subj, ""),
                "teacher_name": _TEACHERS.get(subj, ""),
                "room_name": _ROOMS[n],
                "mark": [8, 12, 10, 9][n % 4] if has_mark else None,
                "attendance": "100" if n != 3 else "75",
                "was": 1 if n != 3 else 0,
                "video_link": None,
            }
            if day_i == 2 and n == 3:
                # демо-екзамен: середа, 4-та пара «Біологія»
                row["lesson_type"] = 1
                row["exam"] = {"evaluation_date": "2026-08-28",
                               "last_file": None}
                row["mark"] = 11
                row["lesson_theme"] = "Екзаменаційна контрольна робота"
            data.append(row)

    return {
        "data": data,
        "start_day": DEMO_MONDAY,
        "end_date": "2026-08-30",
        "first_visit_day": None,
        "last_visit_day": None,
    }
